def normalize_brand(value: str) -> str:
    value = (value or "").strip().lower()
    for alias, brand in BRAND_ALIASES.items():
        if alias in value:
            return brand
    return "generic"


def guide_for(value: str) -> dict:
    return GUIDES[normalize_brand(value)]

